const {chromium}=require('/Users/aeroaswar/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.AXIOM_TEST_URL || 'http://127.0.0.1:8765/#/');
await page.locator('.is-motion-ready').waitFor();
await page.waitForTimeout(800);
await page.screenshot({path:'qa/hero-desktop.png'});
const read=()=>page.locator('.hero-pen').evaluateAll(nodes=>nodes.map(n=>getComputedStyle(n).transform));
const before=await read();
const art=await page.locator('.hero-motion').boundingBox();
await page.mouse.move(art.x+art.width*.8,art.y+art.height*.4);
await page.waitForTimeout(900);
const pointer=await read();assert.notDeepEqual(pointer,before);assert.equal(new Set(pointer).size,3);
await page.screenshot({path:'qa/hero-cursor.png'});
await page.mouse.move(10,10);await page.waitForTimeout(1100);
const reset=await page.locator('.hero-pen').evaluateAll(nodes=>nodes.map(n=>new DOMMatrix(getComputedStyle(n).transform).m41));
assert(reset.every(x=>Math.abs(x)<.02));
const groundBefore=await page.locator('.hero-ground').evaluate(n=>getComputedStyle(n).transform);
await page.evaluate(()=>scrollTo(0,320));await page.waitForTimeout(900);
const scroll=await read();assert.notDeepEqual(scroll,before);
assert.equal(await page.locator('.hero-ground').evaluate(n=>getComputedStyle(n).transform),groundBefore);
await page.screenshot({path:'qa/hero-scroll.png'});
await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(100);
assert.equal(await page.locator('.hero-still').evaluate(n=>getComputedStyle(n).visibility),'visible');
assert.equal(await page.locator('.hero-layers').evaluate(n=>getComputedStyle(n).display),'none');
assert((await read()).every(x=>x==='none'));
await page.emulateMedia({reducedMotion:'no-preference'});
await page.evaluate(()=>{location.hash='/products'});await page.locator('.hero-motion').waitFor({state:'detached'});
await page.evaluate(()=>{location.hash='/'});await page.locator('.is-motion-ready').waitFor();
assert.equal(await page.locator('.hero-motion').count(),1);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto(process.env.AXIOM_TEST_URL || 'http://127.0.0.1:8765/#/');
await mobile.locator('.is-motion-ready').waitFor();
await mobile.evaluate(()=>scrollTo(0,350));await mobile.waitForTimeout(700);
await mobile.screenshot({path:'qa/hero-mobile.png'});
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
assert.equal(await mobile.locator('.hero-cursor-light').evaluate(n=>getComputedStyle(n).opacity),'0');
assert.deepEqual(errors,[]);
console.log(JSON.stringify({result:'PASS',desktopCursor:true,independentPens:true,scrollDepth:true,anchoredStone:true,pointerReset:true,reducedMotion:true,routeRemount:true,mobile:true,noOverflow:true,errors},null,2));
await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
